using NanosSharp.Installer.Client;

namespace NanosSharp.Installer.Tests;

public sealed class KeyValuesTests
{
    [Fact]
    public void LibraryFoldersAreParsed()
    {
        var root = KeyValues.Parse("""
            "libraryfolders"
            {
                "0"
                {
                    "path"		"/home/user/.local/share/Steam"
                    "apps" { "1841660" "123" }
                }
                "1" { "path" "D:\\Games\\Steam" }
            }
            """);

        var folders = root.Child("libraryfolders");
        Assert.NotNull(folders);
        Assert.Equal("/home/user/.local/share/Steam", folders.Child("0")?.Value("path"));
        Assert.Equal("123", folders.Child("0")?.Child("apps")?.Value("1841660"));
        Assert.Equal(@"D:\Games\Steam", folders.Child("1")?.Value("path"));
    }

    [Fact]
    public void KeysAreCaseInsensitiveAndCommentsIgnored()
    {
        var root = KeyValues.Parse("""
            // generated by Steam
            "AppState" { "installdir" "nanos-world" }
            """);

        Assert.Equal("nanos-world", root.Child("appstate")?.Value("InstallDir"));
    }
}
